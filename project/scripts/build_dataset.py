"""Build the TRANSFERFIT historical transfer dataset.

Pipeline:
1. snapshot raw files into project/data/raw (originals untouched)
2. stint panel
3. transfer derivation (clean summer-window + in-season window moves)
4. Real Madrid ledger bridge (named reference list)
5. feature engineering -> historical transfer rows
6. adaptation label
7. processed outputs + data readiness report
"""
from __future__ import annotations

import shutil
import sys
from pathlib import Path

PROJECT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(PROJECT))

from src import config
from src.data_loading import load_namespace_a, load_namespace_b, resolve_player_b2a
from src.preprocessing import build_stint_panel, build_transfers_clean, build_transfers_winter
from src.feature_engineering import build_historical_dataset
from src.adaptation_label import apply_label, label_summary, sensitivity

PROJECT2 = config.PROJECT_DIR


def snapshot_raw():
    for path in config.RAW_SNAPSHOT_FILES:
        if path.exists():
            dst = config.DATA_RAW / path.name
            if not dst.exists():
                shutil.copy2(path, dst)


def main():
    snapshot_raw()
    a = load_namespace_a()
    b = load_namespace_b()

    stint = build_stint_panel(a)
    stint.to_parquet(config.DATA_PROCESSED / "stint_panel.parquet")

    # --- Real Madrid ledger bridge (reference list) -------------------------
    ct = b["club_transfers"].copy()
    bridge = resolve_player_b2a(a["players"], sorted(ct["player_name"].unique()))
    ledger = ct.copy()
    ledger["player_id_A"] = ledger["player_name"].map(
        lambda n: bridge["resolved"][n]["player_id"] if n in bridge["resolved"] else None)
    ledger["bridged"] = ledger["player_id_A"].notna()
    n_ledger = int(ledger["bridged"].sum())
    ledger.to_csv(config.DATA_PROCESSED / "rm_ledger_bridged.csv", index=False)

    # --- transfer derivation -------------------------------------------------
    clean = build_transfers_clean(stint)
    winter = build_transfers_winter(stint)
    transfers = concat_transfers(clean, winter)

    hist = build_historical_dataset(
        transfers, stint, a["players"], a["teams"], a["player_valuations"])
    hist = apply_label(hist)

    config.DATA_PROCESSED.mkdir(parents=True, exist_ok=True)
    hist.to_csv(config.DATA_PROCESSED / "historical_transfers.csv", index=False)

    report_txt = build_report(a, b, stint, clean, winter, hist, ledger, n_ledger, bridge)
    (config.TABLES_DIR / "data_readiness_report.md").write_text(
        report_txt, encoding="utf-8")
    print(report_txt)
    print("\n" + label_summary(hist))
    print("\nLABEL SENSITIVITY")
    print(sensitivity(hist).to_string(index=False))


def concat_transfers(*frames):
    import pandas as pd
    return pd.concat(frames, ignore_index=True)


def build_report(a, b, stint, clean, winter, hist, ledger, n_ledger, bridge):
    lines = []
    add = lines.append
    add("# TRANSFERFIT - Data Readiness Report")
    add("\nReport generated by the dataset build pipeline.")
    add("\n## A. Datasets available")
    add(f"- Namespace A (parquet): {', '.join(sorted(config.FILES))}")
    add(f"- Namespace B (ledger CSVs): {', '.join(sorted(config.FILES_B))}")
    add("- Auxiliary: sample events JSON (one match), Real Madrid La Fabrica workbook, PhD proposal PDF")
    add("Coverage: single competition **La Liga** (competition_id=795), three seasons 2022/23 - 2024/25,")
    add(f"{len(a['players'])} players, {len(stint):,} player-club-season registrations, "
        f"{len(a['player_valuations']):,} valuations.")

    add("\n## B. Datasets relevant to TRANSFERFIT")
    add("- players, player_careers, player_season_stats (spine + total/per90/percent), player_valuations,")
    add("- teams, seasons, super_seasons, areas, competitions (league lookup), club_transfers (ledger)")
    add("\n## C. Datasets not relevant (or secondary)")
    add("- laliga_2022_2025.zip: empty archive (no members)")
    add("- SD-DB(PLAYERS).csv, rm_la_fabrica workbook, PhdIntvProposal.pdf: Real Madrid academy/sale analytics, out of scope")
    add("- club_financial_metrics.csv: Real Madrid only (6 rows)")
    add("- team_full_dossier.csv: contains future predictions (leakage); excluded as features")
    add("- 15946 (1).json: single Barcelona-Alavés match; not league-scale, excluded from model input")

    add("\n## D. Join keys")
    add("- Namespace A joins directly on player_id / team_id / competition_id / super_season_id / player_season_stats_id")
    add("- Namespace B (club_transfers, valuations_full, financials) does NOT share IDs with A")
    add("- Entity resolution: name-based bridge; exact short/full-name match, token-coverage fuzzy, manual verification")
    add(f"  -> {n_ledger} of {len(ledger)} ledger rows bridged to namespace A")
    add(f"- Ambiguous/unresolved ledger names (no LaLiga 22/23-24/25 data): "
        f"{len(bridge['ambiguous'])} ambiguous, {len(bridge['unresolved'])} unresolved")

    add("\n## E. Available pre-transfer features")
    add("- profile: age_at_transfer, role group, foot, height, weight, nationality (Spanish flag)")
    add("- performance (last stint before the move): minutes, appearances, starts, goals, assists, xG, xA,")
    add("  key passes, progressive passes, final-third passes, crosses, through balls, dribbles,")
    add("  defensive actions, interceptions, recoveries, clearances, duels, aerials (+ per-90 and % rates)")
    add("- market value: latest valuation dated strictly before the transfer")
    add("- club context: source/target squad market value, league wins proxy, minutes share, target role share")

    add("\n## F. Available post-transfer outcomes")
    add("- minutes, matches, starts, start ratio, goals+assists per-90 (retention ratio vs pre), xG per-90")

    add("\n## G. Data leakage risks (controls)")
    add("- post-transfer season stats are ONLY used to build the label, never as inputs")
    add("- valuations filtered to valuation_date <= transfer date")
    add("- club context uses only pre-transfer season data")
    add("- team_full_dossier future predictions excluded entirely")
    add("- winter-window moves approximate transfer date (season midpoint) - documented approximation")

    add("\n## H. Missing data")
    add("- pre-transfer performance only available inside La Liga 2022/23-2024/25 (foreign league stints absent)")
    add("- 56/105 ledger rows lack transfer fee; valuations cover ~89.5% of players")
    add("- no match-level, injury, tactical or formation data; no team-level financial statements")
    add("- transfer fees in ledger: 49/105 present; many loans without fee")
    add("- exact transfer dates only for the RM ledger; derived moves use season boundaries/season midpoint")

    add("\n## I. Usable transfer cases")
    add(f"- clean summer-window moves (2022/23->2023/24, 2023/24->2024/25): {len(clean)}")
    add(f"- in-season (winter) moves: {len(winter)}")
    add(f"- feature-complete historical transfers with label: {len(hist)}")
    add(f"- labelled positive rate: {float(hist['label'].mean()):.1%}")
    add(f"- RM ledger rows bridged: {n_ledger}; tracked separately as reference list")

    add("\n## J. Recommended next step")
    add("Build the time-based model on the derived labelled pool, report metrics transparently,")
    add("and use the bridged RM ledger only for illustrative look-ups. Clearly document that the")
    add("prototype transfer history covers three La Liga seasons; a production system needs a")
    add("multi-league, multi-season transfer ledger.")

    add("\n## Provenance")
    add("- Parquet files: private unified DB snapshot (schema `sports`), dated 2026-08-11. License: NEEDS VERIFICATION.")
    add("- club_transfers / valuations_full / financials / dossiers: Transfermarkt-style data. License: NEEDS VERIFICATION (third-party proprietary).")
    add("- events JSON: StatsBomb Open Data structure (exact match not verified). License: NEEDS VERIFICATION.")
    add("- derived processed files are our own output (no external license).")
    return "\n".join(lines)


if __name__ == "__main__":
    main()